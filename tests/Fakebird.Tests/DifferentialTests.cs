using System.Globalization;
using System.Text;
using FirebirdSql.Data.FirebirdClient;
using Xunit.Abstractions;

namespace Fakebird.Tests;

/// <summary>
/// Runs a corpus of SQL against a real Firebird 3 server and against Fakebird and compares the observable
/// results (column names, client types, values and error codes). Enabled when FAKEBIRD_REAL_CS points to a
/// real server, e.g. "DataSource=localhost;Port=3050;Database=/firebird/data/{db}.fdb;User=SYSDBA;Password=masterkey"
/// ({db} is replaced by a unique database name; the database is created and dropped by the test).
/// </summary>
[Collection("server")]
public class DifferentialTests(ServerFixture fx, ITestOutputHelper output)
{
    static readonly string? RealCs = Environment.GetEnvironmentVariable("FAKEBIRD_REAL_CS");

    const string Setup = """
        create table t (id integer not null primary key, s varchar(20), c char(5), n numeric(9,2), d double precision,
                        dt date, ts timestamp, b boolean, big bigint, sm smallint);
        create table child (id integer not null primary key, t_id integer references t(id), v varchar(10) default 'dflt');
        create table ident (id integer generated by default as identity primary key, v varchar(10));
        create sequence seq1;
        create exception ex1 'custom message';
        insert into t values (1, 'abc', 'xy', 12.34, 1.5, '2024-02-29', '2024-02-29 13:14:15.1234', true, 9000000000, 7);
        insert into t values (2, null, null, null, null, null, null, null, null, null);
        insert into t values (3, 'ABC ', 'xy   ', -0.5, -2.25, '1999-12-31', '2000-01-01 00:00:00', false, -1, -7);
        insert into child (id, t_id) values (1, 1);
        insert into ident (v) values ('a');
        insert into ident (v) values ('b');
        """;

    static readonly string[] Corpus =
    [
        "select * from t order by id",
        "select id, s || '-' || c, char_length(c), octet_length(s), upper(s), lower(c), trim(c) from t order by id",
        "select n * 2, n / 3, n + d, d / 3, id / 2, id * 1.5, 7 / 2, 7.0 / 2, -7 / 2, mod(-7, 2) from t where id = 1",
        "select avg(id), avg(n), sum(n), sum(d), count(*), count(s), min(c), max(ts), list(s) from t",
        "select id from t order by s",
        "select id from t order by s desc",
        "select id from t order by s nulls last",
        "select dt + 1, dt - 1, ts + 0.5, ts - dt, dt - date '2000-01-01', cast(ts as time), extract(weekday from dt), extract(yearday from dt) from t where id = 1",
        "select dateadd(month, 1, dt), dateadd(-1 year to dt), datediff(month, dt, date '2025-01-01'), datediff(hour, ts, timestamp '2024-03-01 00:00:00') from t where id = 1",
        "select cast(n as varchar(20)), cast(d as varchar(30)), cast(dt as varchar(20)), cast(ts as varchar(30)), cast(b as varchar(10)), cast(big as varchar(20)) from t where id = 1",
        "select cast('12.345' as numeric(9,2)), cast('  42 ' as integer), cast(2.5 as integer), cast(-2.5 as integer), cast(1e3 as varchar(30)) from rdb$database",
        "select '1' + 1, 1 || 2, 'a' = 'a  ', 'a' like 'a ', c = 'xy' from t where id = 1",
        "select coalesce(s, 'none'), nullif(id, 1), iif(b, 'y', 'n'), decode(id, 1, 'one', 2, 'two', 'other') from t order by id",
        "select substring(s from 2), substring(s from 2 for 1), position('b' in s), left(s, 2), right(s, 2), lpad(s, 6, '*'), rpad(s, 6), replace(s, 'b', 'BB'), reverse(s) from t where id = 1",
        "select round(n, 1), round(n, -1), trunc(n), ceil(n), floor(n), abs(n), sign(n), sqrt(16), power(2, 3), exp(0), ln(1) from t where id = 3",
        "select next value for seq1, gen_id(seq1, 10), gen_id(seq1, 0) from rdb$database",
        "select id, v from ident order by id",
        "insert into ident (v) values ('c') returning id",
        "insert into t (id) values (1)",
        "insert into child (id, t_id) values (2, 99)",
        "delete from t where id = 1",
        "insert into t (id, s) values (10, '123456789012345678901')",
        "update t set n = 99999999.99 * 10 where id = 1",
        "select cast('abc' as integer) from rdb$database",
        "select 1 / 0 from rdb$database",
        "select (select id from t) from rdb$database",
        "execute block as begin exception ex1; end",
        "execute block as begin exception ex1 'other ' || 'text'; end",
        "select count(*), sum(1), max(1) from t where 1 = 0",
        "select id, row_number() over (order by id desc), rank() over (partition by b order by n) from t order by id",
        "select current_user, current_role, char_length(cast(current_timestamp as varchar(30))) from rdb$database",
        "select * from child",
        "select t.id, child.v from t left join child on child.t_id = t.id order by t.id",
        "select distinct b from t order by 1",
        "select first 1 skip 1 id from t order by id",
        "select id from t where id in (1, null) or id not in (2, 3)",
        "select 1 from rdb$database where null = null",
        "select cast(null as integer), null from rdb$database",
        "select cast(ts as date), cast(dt as timestamp) from t where id = 1",
        "select uuid_to_char(char_to_uuid('A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11')) from rdb$database",
        "select 2147483647 + 1, 9223372036854775807 from rdb$database",
        "select sm * sm, sm + 1, big + 1 from t where id = 1",
    ];

    static string Describe(FbConnection cn, FbTransaction tx, string sql)
    {
        var sb = new StringBuilder();
        try
        {
            using var cmd = new FbCommand(sql, cn, tx);
            using var r = cmd.ExecuteReader();
            for (var i = 0; i < r.FieldCount; i++)
                sb.Append(r.GetName(i)).Append(':').Append(r.GetDataTypeName(i)).Append(' ');
            sb.AppendLine();
            while (r.Read())
            {
                for (var i = 0; i < r.FieldCount; i++)
                {
                    var v = r.IsDBNull(i) ? null : r.GetValue(i);
                    sb.Append(v switch
                    {
                        null => "NULL",
                        byte[] bytes => Convert.ToHexString(bytes),
                        DateTime d => d.ToString("yyyy-MM-dd HH:mm:ss.ffff", CultureInfo.InvariantCulture),
                        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
                        _ => v.ToString(),
                    }).Append(" | ");
                }
                sb.AppendLine();
            }
        }
        catch (FbException e)
        {
            sb.Append("ERROR ").Append(e.ErrorCode).Append(' ').Append(e.SQLSTATE);
        }
        return sb.ToString().Replace("\r", "");
    }

    static List<string> Run(string cs)
    {
        using var cn = new FbConnection(cs);
        cn.Open();
        using var tx = cn.BeginTransaction();
        var results = Corpus.Select(sql => Describe(cn, tx, sql)).ToList();
        tx.Rollback();
        return results;
    }

    static void RunScript(string cs, string script)
    {
        using var cn = new FbConnection(cs);
        cn.Open();
        foreach (var stmt in ScriptRunner.Split(script))
        {
            using var cmd = new FbCommand(stmt, cn);
            cmd.ExecuteNonQuery();
        }
    }

    [Fact]
    public void FakeMatchesRealFirebird()
    {
        if (RealCs == null)
        {
            // still exercise the corpus against the fake: it must never hit an internal error
            var only = fx.Server.CreateDatabase("diff_" + Guid.NewGuid().ToString("N"));
            only.RunScript(Setup);
            var res = Run(only.ConnectionString());
            for (var i = 0; i < Corpus.Length; i++) output.WriteLine($"--- {Corpus[i]}\n{res[i]}");
            Assert.DoesNotContain(res, r => r.Contains("335544382"));
            return;
        }
        var dbName = "diff_" + Guid.NewGuid().ToString("N")[..8];
        var realCs = RealCs.Replace("{db}", dbName);
        FbConnection.CreateDatabase(realCs, pageSize: 8192, forcedWrites: false, overwrite: true);
        try
        {
            RunScript(realCs, Setup);
            var fake = fx.Server.CreateDatabase(dbName);
            fake.RunScript(Setup);
            var real = Run(realCs);
            var mine = Run(fake.ConnectionString());
            var diffs = new StringBuilder();
            for (var i = 0; i < Corpus.Length; i++)
                if (real[i] != mine[i])
                    diffs.AppendLine($"--- {Corpus[i]}\nreal:\n{real[i]}\nfake:\n{mine[i]}\n");
            output.WriteLine(diffs.Length == 0 ? "all statements match" : diffs.ToString());
            Assert.True(diffs.Length == 0, diffs.ToString());
        }
        finally
        {
            FbConnection.ClearAllPools();
            FbConnection.DropDatabase(realCs);
        }
    }
}
