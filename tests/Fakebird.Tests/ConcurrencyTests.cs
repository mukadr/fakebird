using FirebirdSql.Data.FirebirdClient;

namespace Fakebird.Tests;

[Collection("server")]
public class ConcurrencyTests(ServerFixture fx)
{
    [Fact]
    public async Task ParallelClientsOnOneDatabase()
    {
        var db = fx.Server.CreateDatabase("conc_" + Guid.NewGuid().ToString("N"));
        db.RunScript("""
            create table counter (id integer primary key, n integer not null);
            create table events (id integer generated by default as identity primary key, worker integer, payload varchar(50));
            insert into counter values (1, 0);
            """);
        var cs = db.ConnectionString();
        var wait = new FbTransactionOptions { TransactionBehavior = FbTransactionBehavior.Wait | FbTransactionBehavior.ReadCommitted | FbTransactionBehavior.RecVersion };
        var conflicts = 0;
        var tasks = Enumerable.Range(0, 16).Select(w => Task.Run(async () =>
        {
            await using var cn = new FbConnection(cs);
            await cn.OpenAsync();
            for (var i = 0; i < 100; i++)
            {
                await using var tx = await cn.BeginTransactionAsync(wait);
                await using (var ins = new FbCommand("insert into events (worker, payload) values (@w, @p)", cn, tx))
                {
                    ins.Parameters.AddWithValue("@w", w);
                    ins.Parameters.AddWithValue("@p", $"w{w} i{i}");
                    await ins.ExecuteNonQueryAsync();
                }
                try
                {
                    await using var upd = new FbCommand("update counter set n = n + 1 where id = 1", cn, tx);
                    await upd.ExecuteNonQueryAsync();
                    await tx.CommitAsync();
                }
                catch (FbException e) when (e.ErrorCode == 335544336)
                {
                    Interlocked.Increment(ref conflicts);
                    await tx.RollbackAsync();
                }
            }
        })).ToArray();
        await Task.WhenAll(tasks);
        await using var check = new FbConnection(cs);
        await check.OpenAsync();
        await using var c1 = new FbCommand("select n from counter", check);
        var n = (int)(await c1.ExecuteScalarAsync())!;
        await using var c2 = new FbCommand("select count(*) from events", check);
        var events = (long)(await c2.ExecuteScalarAsync())!;
        Assert.Equal(1600, n + conflicts);
        Assert.Equal(n, events); // only committed transactions left their event row
    }

    [Fact]
    public async Task ParallelTestsWithOwnClones()
    {
        var template = fx.Server.CreateDatabase("tpl_" + Guid.NewGuid().ToString("N"));
        template.RunScript("""
            create table item (id integer primary key, name varchar(20));
            insert into item values (1, 'a');
            insert into item values (2, 'b');
            """);
        var snap = template.Snapshot();
        var tasks = Enumerable.Range(0, 32).Select(t => Task.Run(async () =>
        {
            var db = fx.Server.CreateDatabase($"clone_{t}_{Guid.NewGuid():N}", snap);
            await using var cn = new FbConnection(db.ConnectionString());
            await cn.OpenAsync();
            for (var i = 0; i < 50; i++)
            {
                await using var ins = new FbCommand($"insert into item values ({100 + i}, 't{t}')", cn);
                await ins.ExecuteNonQueryAsync();
            }
            await using var cnt = new FbCommand("select count(*) from item", cn);
            Assert.Equal(52L, await cnt.ExecuteScalarAsync());
        })).ToArray();
        await Task.WhenAll(tasks);
        await using var tcn = new FbConnection(template.ConnectionString());
        await tcn.OpenAsync();
        await using var tc = new FbCommand("select count(*) from item", tcn);
        Assert.Equal(2L, await tc.ExecuteScalarAsync());
    }
}
