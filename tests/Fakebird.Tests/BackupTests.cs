using System.Text;
using Fakebird.Engine;
using FirebirdSql.Data.FirebirdClient;

namespace Fakebird.Tests;

/// <summary>Backup files: a restored database shows the same catalog and rows, and carries on from there.</summary>
public class BackupTests
{
    const string Schema = """
        create domain d_qty as numeric(12,3) default 1 not null check (value >= 0);
        create domain d_name as varchar(40) character set win1252 collate win1252;
        create sequence seq_doc start with 100 increment by 5;
        create exception e_bad 'bad value: @1';
        create table customer (
          id integer generated by default as identity primary key,
          name d_name not null,
          code varchar(10) unique,
          email varchar(60) collate unicode_ci,
          created timestamp default current_timestamp,
          constraint ck_code check (code is null or char_length(code) > 1));
        create table doc (
          id bigint not null,
          customer_id integer references customer (id) on delete cascade,
          qty d_qty,
          price numeric(18,4),
          big numeric(38,2),
          ratio double precision,
          ratio_f float,
          flag boolean,
          notes blob sub_type text,
          image blob sub_type binary,
          raw char(4) character set octets,
          doc_day date,
          at_time time,
          at_tz timestamp with time zone,
          t_tz time with time zone,
          total computed by (qty * price),
          constraint pk_doc primary key (id));
        create descending index ix_doc_day on doc (doc_day);
        create index ix_doc_flag on doc (flag);
        alter index ix_doc_flag inactive;
        create global temporary table gtt_work (id integer) on commit preserve rows;
        create view v_doc (id, customer, total) as select d.id, c.name, d.total from doc d join customer c on c.id = d.customer_id;
        comment on table doc is 'documents';
        comment on column doc.qty is 'quantity';
        set term ^;
        create procedure p_docs (cid integer, minimum numeric(18,4) = 0) returns (id bigint, total numeric(18,4)) as
        begin
          for select id, total from doc where customer_id = :cid and total >= :minimum into :id, :total do
            suspend;
        end^
        create function f_twice (x integer) returns integer deterministic as
        begin
          return x * 2;
        end^
        create trigger doc_bi for doc before insert position 5
        as
        begin
          if (new.id is null) then new.id = next value for seq_doc;
          if (new.price < 0) then
            exception e_bad new.price;
        end^
        set term ;^
        insert into customer (name, code, email) values ('Ação Ltda', 'AC', 'A@x.com');
        insert into customer (name, code, email) values ('Beta', null, null);
        insert into doc (customer_id, qty, price, big, ratio, ratio_f, flag, notes, image, raw, doc_day, at_time, at_tz, t_tz)
          values (1, 2.5, 10.1234, 12345678901234567890123.45, 1.0e-300, 0.1, true, 'long text', x'00FF10', x'01020304',
                  date '2026-10-29', time '13:14:15.1234', timestamp '2026-10-29 10:00:00 America/Sao_Paulo', time '10:00 +03:00');
        insert into doc (customer_id, qty, price) values (2, 1, 3);
        insert into doc (id, customer_id) values (7, null);
        delete from doc where id = 7;
        """;

    static string Dump(FakebirdServer server, string name)
    {
        var db = server.Engine(name);
        var fake = server.GetDatabase(name);
        var sb = new StringBuilder();
        List<string> tables;
        lock (db.Sync) tables = db.Tables.Values.Where(t => !t.IsGtt && (!t.IsSystem || t.Name.StartsWith("RDB$"))).Select(t => t.Name).Order().ToList();
        foreach (var t in tables)
        {
            sb.Append("== ").AppendLine(t);
            var sql = db.Tables[t].IsSystem ? $"select * from {t}" : $"select rdb$db_key, t.* from {t} t";
            foreach (var row in fake.Execute(sql).Select(r => string.Join(" | ", r.Select(Show))).Order(StringComparer.Ordinal))
                sb.AppendLine(row);
        }
        return sb.ToString();
    }

    static string Show(object? o) => o switch
    {
        null => "NULL",
        byte[] b => Convert.ToHexString(b),
        IFormattable f => f.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
        _ => o.ToString()!,
    };

    static byte[] BackupOf(FakebirdServer server)
    {
        var ms = new MemoryStream();
        server.Backup(ms);
        return ms.ToArray();
    }

    [Fact]
    public void RoundTripKeepsCatalogAndRows()
    {
        using var a = FakebirdServer.Start();
        var db = a.CreateDatabase("demo", charset: "WIN1252");
        db.DefaultTimeZone = "America/Sao_Paulo";
        db.RunScript(Schema);
        a.CreateDatabase("other").RunScript("create table x (v varchar(5)); insert into x values ('hi');");

        using var b = FakebirdServer.Start();
        b.RestoreBackup(new MemoryStream(BackupOf(a)));

        Assert.Equal(Dump(a, "demo"), Dump(b, "demo"));
        Assert.Equal(Dump(a, "other"), Dump(b, "other"));
        Assert.Equal("America/Sao_Paulo", b.GetDatabase("demo").DefaultTimeZone);
        Assert.Equal("WIN1252", b.GetDatabase("demo").DefaultCharset);
        // a backup of the restored server is the same backup, apart from when it was made
        static string Body(byte[] backup) => Encoding.UTF8.GetString(backup).Split("\"databases\"")[1];
        Assert.Equal(Body(BackupOf(a)), Body(BackupOf(b)));
    }

    [Fact]
    public void RestoredDatabaseCarriesOn()
    {
        using var a = FakebirdServer.Start();
        a.CreateDatabase("demo").RunScript(Schema);
        using var b = FakebirdServer.Start();
        b.RestoreBackup(new MemoryStream(BackupOf(a)));
        var db = b.GetDatabase("demo");

        // sequences, identities and the trigger continue where they were
        db.RunScript("insert into customer (name) values ('Gamma'); insert into doc (customer_id, qty, price) values (3, 1, 1);");
        Assert.Equal(3L, db.Execute("select max(id) from customer").Single()[0]);
        Assert.Equal(110L, db.Execute("select max(id) from doc").Single()[0]);
        Assert.Equal(115L, db.Execute("select next value for seq_doc from rdb$database").Single()[0]);
        // stored code runs
        Assert.Equal(25.3085m, db.Execute("select total from p_docs(1)").Single()[0]);
        Assert.Equal(42L, db.Execute("select f_twice(21) from rdb$database").Single()[0]);
        Assert.Equal("Ação Ltda", db.Execute("select customer from v_doc where id = 100").Single()[0]);
        // constraints, domains and collations are enforced
        Assert.ThrowsAny<Exception>(() => db.Execute("insert into customer (name, code) values ('Dup', 'AC')"));
        Assert.ThrowsAny<Exception>(() => db.Execute("insert into doc (id, customer_id) values (1, 99)"));
        Assert.ThrowsAny<Exception>(() => db.Execute("insert into doc (id, qty) values (1, -1)"));
        Assert.ThrowsAny<Exception>(() => db.Execute("insert into customer (name, code) values ('Short', 'x')"));
        Assert.Equal(1L, db.Execute("select id from customer where email = 'a@X.COM'").Single()[0]);
        db.Execute("delete from customer where id = 1");
        Assert.Empty(db.Execute("select * from doc where customer_id = 1"));
        // new rows get keys after the restored ones
        var keys = db.Execute("select rdb$db_key from doc").Select(r => Convert.ToHexString((byte[])r[0]!)).ToList();
        Assert.Equal(keys.Order(StringComparer.Ordinal), keys);
    }

    [Fact]
    public void PsqlErrorsReportTheOriginalPositions()
    {
        using var a = FakebirdServer.Start();
        a.CreateDatabase("demo").RunScript(Schema);
        using var b = FakebirdServer.Start();
        b.RestoreBackup(new MemoryStream(BackupOf(a)));
        string Error(FakebirdServer s)
            => Assert.ThrowsAny<Exception>(() => s.GetDatabase("demo").Execute("insert into doc (id, price) values (1, -1)")).Message;
        Assert.Contains("line:", Error(a));
        Assert.Equal(Error(a), Error(b));
    }

    [Fact]
    public void BackupLeavesOutUncommittedWork()
    {
        using var a = FakebirdServer.Start();
        var db = a.CreateDatabase("demo");
        db.RunScript("create table t (id integer); insert into t values (1);");
        using var cn = new FbConnection(db.ConnectionString());
        cn.Open();
        using var tx = cn.BeginTransaction();
        new FbCommand("insert into t values (2)", cn, tx).ExecuteNonQuery();
        var backup = BackupOf(a);
        tx.Commit();

        using var b = FakebirdServer.Start();
        b.RestoreBackup(new MemoryStream(backup));
        Assert.Equal(1L, b.GetDatabase("demo").Execute("select id from t").Single()[0]);
    }

    [Fact]
    public void RestoreReplacesDatabasesAndReattachesPooledConnections()
    {
        using var a = FakebirdServer.Start();
        var db = a.CreateDatabase("demo");
        db.RunScript("create table t (id integer); insert into t values (1);");
        var path = Path.Combine(Path.GetTempPath(), "fakebird-" + Guid.NewGuid().ToString("N") + ".json");
        try
        {
            a.Backup(path);
            var keep = a.CreateDatabase("untouched");
            db.RunScript("insert into t values (2); create table extra (x integer);");
            var cs = db.ConnectionString();
            using (var cn = new FbConnection(cs))
            {
                cn.Open();
                Assert.Equal(2L, new FbCommand("select count(*) from t", cn).ExecuteScalar());
            }

            a.RestoreBackup(path);
            using (var cn = new FbConnection(cs))
            {
                cn.Open();
                Assert.Equal(1L, new FbCommand("select count(*) from t", cn).ExecuteScalar());
            }
            Assert.Empty(db.Execute("select * from rdb$relations where rdb$relation_name = 'EXTRA'"));
            Assert.Equal("untouched", a.GetDatabase("untouched").Name);
            Assert.False(File.Exists(path + ".tmp"));
        }
        finally
        {
            File.Delete(path);
            FbConnection.ClearAllPools();
        }
    }

    [Fact]
    public void UnreadableBackupChangesNothing()
    {
        using var a = FakebirdServer.Start();
        a.CreateDatabase("demo").RunScript("create table t (id integer); insert into t values (1);");
        var backup = System.Text.Json.Nodes.JsonNode.Parse(BackupOf(a))!;
        Assert.Throws<FormatException>(() => a.RestoreBackup(new MemoryStream("{\"format\":\"other\"}"u8.ToArray())));
        // a broken database in the backup: the good one is not restored either
        backup["databases"]!.AsArray().Add(new System.Text.Json.Nodes.JsonObject { ["name"] = "bad" });
        a.GetDatabase("demo").RunScript("insert into t values (2);");
        Assert.ThrowsAny<Exception>(() => a.RestoreBackup(new MemoryStream(Encoding.UTF8.GetBytes(backup.ToJsonString()))));
        Assert.Equal(2L, a.GetDatabase("demo").Execute("select count(*) from t").Single()[0]);
    }
}
