using FirebirdSql.Data.FirebirdClient;

namespace Fakebird.Tests;

[Collection("server")]
public class PsqlTests(ServerFixture fx)
{
    static object? Scalar(FbConnection cn, string sql)
    {
        using var cmd = new FbCommand(sql, cn);
        var v = cmd.ExecuteScalar();
        return v is DBNull ? null : v;
    }

    static List<object?[]> Rows(FbConnection cn, string sql)
    {
        using var cmd = new FbCommand(sql, cn);
        using var r = cmd.ExecuteReader();
        var list = new List<object?[]>();
        while (r.Read())
        {
            var row = new object?[r.FieldCount];
            for (var i = 0; i < row.Length; i++) row[i] = r.IsDBNull(i) ? null : r.GetValue(i);
            list.Add(row);
        }
        return list;
    }

    static void Exec(FbConnection cn, string sql)
    {
        using var cmd = new FbCommand(sql, cn);
        cmd.ExecuteNonQuery();
    }

    const string Schema = """
        create table acc (id integer primary key, owner varchar(20), balance numeric(12,2) default 0 not null);
        create table audit (id integer generated by default as identity primary key, what varchar(100));
        create exception insufficient 'insufficient funds';
        insert into acc values (1, 'ann', 100);
        insert into acc values (2, 'bob', 50);
        insert into acc values (3, 'cid', 0);
        """;

    [Fact]
    public void CursorsLabelsAndRowCount()
    {
        using var cn = fx.NewDatabase(Schema);
        var r = Rows(cn, """
            execute block returns (total numeric(12,2), names varchar(100), updated integer, loops integer) as
            declare c cursor for (select owner, balance from acc order by id);
            declare o varchar(20);
            declare b numeric(12,2);
            begin
              total = 0; names = ''; loops = 0;
              open c;
              while (1 = 1) do
              begin
                fetch c into :o, :b;
                if (row_count = 0) then leave;
                total = total + b;
                names = names || o;
              end
              close c;
              update acc set balance = balance + 1 where balance > 10;
              updated = row_count;
              outer_loop:
              for select id from acc into :b as cursor cur do
              begin
                while (1 = 1) do
                begin
                  loops = loops + 1;
                  if (cur.id = 2) then leave outer_loop;
                  leave;
                end
              end
              suspend;
            end
            """).Single();
        Assert.Equal(150m, r[0]);
        Assert.Equal("annbobcid", r[1]);
        Assert.Equal(2, r[2]);
        Assert.Equal(2, r[3]);
    }

    [Fact]
    public void HandlersUndoBlockEffectsAndReraise()
    {
        using var cn = fx.NewDatabase(Schema + """
            set term ^ ;
            create procedure transfer (src integer, dst integer, amt numeric(12,2)) as
            begin
              update acc set balance = balance + :amt where id = :dst;
              update acc set balance = balance - :amt where id = :src;
              if ((select balance from acc where id = :src) < 0) then exception insufficient;
            end^
            create procedure try_transfer (src integer, dst integer, amt numeric(12,2)) returns (result varchar(50)) as
            begin
              result = 'ok';
              begin
                insert into audit (what) values ('attempt');
                execute procedure transfer :src, :dst, :amt;
                when exception insufficient do
                  result = 'failed: ' || sqlcode;
              end
            end^
            create procedure rethrow as
            begin
              begin
                exception insufficient 'deep';
                when any do
                begin
                  insert into audit (what) values ('handled');
                  exception;
                end
              end
            end^
            set term ; ^
            """);
        Assert.Equal("failed: -836", Scalar(cn, "execute procedure try_transfer 3, 1, 10"));
        Assert.Equal(100m, Scalar(cn, "select balance from acc where id = 1")); // undone
        Assert.Equal(0L, Scalar(cn, "select count(*) from audit")); // block effects undone, including the insert
        Assert.Equal("ok", Scalar(cn, "execute procedure try_transfer 1, 3, 10"));
        Assert.Equal(10m, Scalar(cn, "select balance from acc where id = 3"));
        var ex = Assert.Throws<FbException>(() => Exec(cn, "execute procedure rethrow"));
        Assert.Contains("deep", ex.Message);
        Assert.Equal(1L, Scalar(cn, "select count(*) from audit")); // 'attempt' from the successful transfer only
        // GDSCODE / SQLSTATE handlers
        Assert.Equal("dup", Scalar(cn, """
            execute block returns (r varchar(10)) as
            begin
              r = 'none';
              begin
                insert into acc (id, owner) values (1, 'x');
                when gdscode unique_key_violation do r = 'dup';
              end
              suspend;
            end
            """));
        Assert.Equal("state", Scalar(cn, """
            execute block returns (r varchar(10)) as
            begin
              begin
                r = 1 / 0;
                when sqlstate '22012' do r = 'state';
              end
              suspend;
            end
            """));
    }

    [Fact]
    public void TriggersOrderMultiEventAndRecursion()
    {
        using var cn = fx.NewDatabase(Schema + """
            set term ^ ;
            create trigger acc_biu_2 for acc active before insert or update position 2 as
            begin
              new.owner = upper(new.owner);
            end^
            create trigger acc_biu_1 for acc active before insert or update position 1 as
            begin
              new.owner = new.owner || '!';
            end^
            create trigger acc_aiud for acc after insert or update or delete as
            begin
              insert into audit (what) values (
                case when inserting then 'I ' || new.id when updating then 'U ' || new.id else 'D ' || old.id end);
            end^
            create procedure fact (n integer) returns (r bigint) as
            begin
              if (n <= 1) then r = 1;
              else
              begin
                execute procedure fact :n - 1 returning_values :r;
                r = r * n;
              end
            end^
            set term ; ^
            """);
        Exec(cn, "insert into acc (id, owner) values (4, 'dan')");
        Assert.Equal("DAN!", Scalar(cn, "select owner from acc where id = 4"));
        Exec(cn, "update acc set balance = 5 where id = 4");
        Exec(cn, "delete from acc where id = 4");
        var audit = Rows(cn, "select what from audit order by id").Select(x => (string)x[0]!).ToArray();
        Assert.Equal(["I 4", "U 4", "D 4"], audit);
        Assert.Equal(3628800L, Scalar(cn, "execute procedure fact 10"));
    }

    [Fact]
    public void AutonomousTransactionsSubRoutinesAndDynamicSql()
    {
        using var cn = fx.NewDatabase(Schema);
        using (var tx = cn.BeginTransaction())
        {
            using var cmd = new FbCommand("""
                execute block as
                begin
                  in autonomous transaction do
                    insert into audit (what) values ('kept');
                  insert into audit (what) values ('rolled back');
                end
                """, cn, tx);
            cmd.ExecuteNonQuery();
            tx.Rollback();
        }
        Assert.Equal("kept", Scalar(cn, "select list(what) from audit"));
        Assert.Equal(6, Scalar(cn, """
            execute block returns (r integer) as
              declare function sq (x integer) returns integer as begin return x * x; end
              declare procedure gen (n integer) returns (i integer) as
              begin
                i = 0;
                while (i < n) do begin i = i + 1; suspend; end
              end
            begin
              r = sq(2) + (select sum(i) from gen(2)) - 1;
              suspend;
            end
            """));
        Assert.Equal(2L, Scalar(cn, """
            execute block returns (n bigint) as
            begin
              execute statement ('select count(*) from acc where balance >= ?') (10) into :n;
              suspend;
            end
            """));
        Assert.Equal("ann,bob,cid", Scalar(cn, """
            execute block returns (s varchar(100)) as
            declare o varchar(20);
            begin
              s = '';
              for execute statement 'select owner from acc order by id' into :o do
                s = s || iif(s = '', '', ',') || o;
              suspend;
            end
            """));
    }

    [Fact]
    public void ContextVariablesAndUdf()
    {
        using var cn = fx.NewDatabase();
        Assert.Equal("v1", Scalar(cn, """
            execute block returns (r varchar(10)) as
            begin
              rdb$set_context('USER_TRANSACTION', 'k', 'v1');
              r = rdb$get_context('USER_TRANSACTION', 'k');
              suspend;
            end
            """));
        Exec(cn, "select rdb$set_context('USER_SESSION', 'tenant', '42') from rdb$database");
        Assert.Equal("42", Scalar(cn, "select rdb$get_context('USER_SESSION', 'tenant') from rdb$database"));
        Assert.Equal("5.0.4", Scalar(cn, "select rdb$get_context('SYSTEM', 'ENGINE_VERSION') from rdb$database"));
    }
}
