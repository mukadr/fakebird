using FirebirdSql.Data.FirebirdClient;

namespace Fakebird.Tests;

[Collection("server")]
public class WireTests(ServerFixture fx)
{
    [Fact]
    public void ConnectAndSelect()
    {
        using var cn = fx.NewDatabase();
        Assert.Contains("Firebird", cn.ServerVersion + " Firebird");
        using var cmd = new FbCommand("select 1, 'abc', cast(2.50 as numeric(9,2)) from rdb$database", cn);
        using var r = cmd.ExecuteReader();
        Assert.True(r.Read());
        Assert.Equal(1, r.GetInt32(0));
        Assert.Equal("abc", r.GetString(1));
        Assert.Equal(2.50m, r.GetDecimal(2));
        Assert.False(r.Read());
    }

    [Fact]
    public void ParametersTransactionsAndErrors()
    {
        using var cn = fx.NewDatabase("""
            create table person (
              id integer not null primary key,
              name varchar(50) not null,
              born date,
              balance numeric(15,2) default 0,
              active boolean default true,
              notes blob sub_type text,
              created timestamp default current_timestamp
            );
            """);
        using (var tx = cn.BeginTransaction())
        {
            using var ins = new FbCommand("insert into person (id, name, born, notes) values (@id, @name, @born, @notes)", cn, tx);
            ins.Parameters.AddWithValue("@id", 1);
            ins.Parameters.AddWithValue("@name", "Ana");
            ins.Parameters.AddWithValue("@born", new DateTime(1990, 5, 17));
            ins.Parameters.AddWithValue("@notes", new string('x', 100_000));
            Assert.Equal(1, ins.ExecuteNonQuery());
            tx.Commit();
        }
        using (var cmd = new FbCommand("select name, born, balance, active, notes, created from person where id = @id", cn))
        {
            cmd.Parameters.AddWithValue("@id", 1);
            using var r = cmd.ExecuteReader();
            Assert.True(r.Read());
            Assert.Equal("Ana", r.GetString(0));
            Assert.Equal(new DateTime(1990, 5, 17), r.GetDateTime(1));
            Assert.Equal(0m, r.GetDecimal(2));
            Assert.True(r.GetBoolean(3));
            Assert.Equal(100_000, r.GetString(4).Length);
            Assert.True((DateTime.Now - r.GetDateTime(5)).TotalMinutes < 5);
        }
        var ex = Assert.Throws<FbException>(() =>
        {
            using var dup = new FbCommand("insert into person (id, name) values (1, 'dup')", cn);
            dup.ExecuteNonQuery();
        });
        Assert.Equal(335544665, ex.ErrorCode);
        Assert.Contains("PRIMARY or UNIQUE KEY", ex.Message);

        using (var tx = cn.BeginTransaction())
        {
            using var del = new FbCommand("delete from person", cn, tx);
            Assert.Equal(1, del.ExecuteNonQuery());
            tx.Rollback();
        }
        using var count = new FbCommand("select count(*) from person", cn);
        Assert.Equal(1L, count.ExecuteScalar());
    }

    [Fact]
    public void ReturningAndStoredProcedures()
    {
        using var cn = fx.NewDatabase("""
            create table item (id integer generated by default as identity primary key, name varchar(20));
            set term ^ ;
            create procedure add_item (n varchar(20)) returns (new_id integer) as
            begin
              insert into item (name) values (:n) returning id into :new_id;
            end^
            create procedure numbers (cnt integer) returns (n integer) as
            begin
              n = 0;
              while (n < cnt) do begin n = n + 1; suspend; end
            end^
            set term ; ^
            """);
        using (var cmd = new FbCommand("insert into item (name) values ('a') returning id", cn))
            Assert.Equal(1, cmd.ExecuteScalar());
        using (var cmd = new FbCommand("execute procedure add_item 'b'", cn))
            Assert.Equal(2, cmd.ExecuteScalar());
        using (var cmd = new FbCommand("add_item", cn) { CommandType = System.Data.CommandType.StoredProcedure })
        {
            cmd.Parameters.Add("n", FbDbType.VarChar).Value = "c";
            cmd.Parameters.Add("new_id", FbDbType.Integer).Direction = System.Data.ParameterDirection.Output;
            cmd.ExecuteNonQuery();
            Assert.Equal(3, cmd.Parameters["new_id"].Value);
        }
        using (var cmd = new FbCommand("select sum(n) from numbers(10)", cn))
            Assert.Equal(55L, cmd.ExecuteScalar());
    }

    [Fact]
    public void Guids()
    {
        using var cn = fx.NewDatabase("create table g (id char(16) character set octets primary key, v varchar(10));");
        var id = Guid.NewGuid();
        using (var cmd = new FbCommand("insert into g values (@id, 'x')", cn))
        {
            cmd.Parameters.AddWithValue("@id", id);
            cmd.ExecuteNonQuery();
        }
        using (var cmd = new FbCommand("select id, uuid_to_char(id) from g where id = @id", cn))
        {
            cmd.Parameters.AddWithValue("@id", id);
            using var r = cmd.ExecuteReader();
            Assert.True(r.Read());
            Assert.Equal(id, r.GetGuid(0));
            Assert.Equal(id.ToString().ToUpperInvariant(), r.GetString(1));
        }
    }
}
