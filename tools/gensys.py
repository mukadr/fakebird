#!/usr/bin/env python3
"""Generates src/Fakebird/Engine/SystemSchema.g.cs: the columns of Firebird's system tables (RDB$, MON$, SEC$)
with their types and nullability, from Firebird's src/jrd/{names,fields,relations}.h.

usage: tools/gensys.py <firebird-source>/src/jrd > src/Fakebird/Engine/SystemSchema.g.cs
"""
import re, sys, os

jrd = sys.argv[1]
names = dict((m.group(2), m.group(1)) for m in re.finditer(r'NAME\("([^"]+)",\s*(\w+)\)', open(os.path.join(jrd, "names.h")).read()))

CONST = {"MAX_SQL_IDENTIFIER_LEN": 252, "METADATA_BYTES_PER_CHAR": 4, "USERNAME_LENGTH": 252,
         "METADATA_IDENTIFIER_CHAR_LEN": 63, "MAX_CONFIG_NAME_LEN": 63, "MAX_VARY_COLUMN_SIZE": 32765}

def length(expr):
    expr = expr.strip()
    for k, v in CONST.items():
        expr = expr.replace(k, str(v))
    return int(eval(expr)) if re.fullmatch(r'[\d\s*+]+', expr) else 0

CHARSET = {"dsc_text_type_metadata": ("Utf8", 4), "dsc_text_type_ascii": ("Ascii", 1),
           "dsc_text_type_fixed": ("Octets", 1), "0": ("None", 1)}
BLOB = {"isc_blob_text": 1, "isc_blob_blr": 2, "isc_blob_acl": 3, "isc_blob_untyped": 0, "isc_blob_ranges": 4,
        "isc_blob_summary": 5, "isc_blob_format": 6, "isc_blob_tra": 7, "isc_blob_extfile": 8, "isc_blob_debug_info": 9}

fields = {}
for m in re.finditer(r'^\s*FIELD\((\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,([^,]+),([^,]+),[^,]+,\s*(\w+)\s*,', open(os.path.join(jrd, "fields.h")).read(), re.M):
    fld, _, dtype, ln, sub, nullable = m.groups()
    sub = sub.strip()
    if dtype in ("dtype_text", "dtype_varying"):
        cs, bpc = CHARSET[sub]
        kind = "Char" if dtype == "dtype_text" else "VarChar"
        t = f"SqlType.{kind}({max(1, length(ln) // bpc)}, Charset.{cs})"
    elif dtype == "dtype_blob":
        st = BLOB.get(sub, 0)
        t = "new SqlType(TypeKind.Blob, subType: 1, charset: Charset.Utf8)" if st == 1 else f"new SqlType(TypeKind.Blob, subType: {st})"
    else:
        t = {"dtype_short": "SqlType.SmallInt", "dtype_long": "SqlType.Integer", "dtype_int64": "SqlType.BigInt",
             "dtype_double": "SqlType.Double", "dtype_boolean": "SqlType.Boolean", "dtype_timestamp": "SqlType.Timestamp",
             # Firebird 5 with DataTypeCompatibility 3.0 describes TIMESTAMP WITH TIME ZONE as TIMESTAMP
             "dtype_timestamp_tz": "SqlType.Timestamp"}[dtype]
    fields[fld] = (t, nullable == "true")

out = []
rel = None
for line in open(os.path.join(jrd, "relations.h")):
    m = re.match(r'\s*RELATION\((\w+),', line)
    if m:
        rel = (names[m.group(1)], [])
        continue
    m = re.match(r'\s*FIELD\((\w+),\s*(\w+),\s*(\w+),', line)
    if m and rel:
        t, nullable = fields[m.group(3)]
        rel[1].append((names[m.group(2)], t, nullable))
        continue
    if line.strip().startswith("END_RELATION") and rel:
        out.append(rel)
        rel = None

print("""// <auto-generated> by tools/gensys.py from Firebird's src/jrd/{names,fields,relations}.h </auto-generated>
// The system relation definitions are part of Firebird (Initial Developer's Public License / InterBase Public License).
using Fakebird.Types;

namespace Fakebird.Engine;

/// <summary>Columns of Firebird 5's system tables: name, type and nullability, in field order.</summary>
internal static class SystemSchema
{
    internal static readonly Dictionary<string, (string Name, SqlType Type, bool Nullable)[]> Relations = new()
    {""")
for name, cols in out:
    print(f'        ["{name}"] =')
    print("        [")
    for c, t, n in cols:
        print(f'            ("{c}", {t}, {"true" if n else "false"}),')
    print("        ],")
print("""    };
}""")
