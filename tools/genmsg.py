#!/usr/bin/env python3
"""Generates src/Fakebird/FbMessages.g.cs from Firebird's message headers.

usage: tools/genmsg.py <firebird-source>/src/include/firebird/impl/msg > src/Fakebird/FbMessages.g.cs
"""
import re, sys, os

FACILITIES = {"JRD": 0, "DSQL": 7, "DYN": 8, "SQLERR": 13, "SQLWARN": 14}
MSG = re.compile(r'^FB_IMPL_MSG\((\w+), (\d+), (\w+), (-?\d+), "(\w*)", "(\w*)", "((?:[^"\\]|\\.)*)"\)')
# private messages (no symbol, SQLCODE or SQLSTATE) are named <facility>_<number>
NOSYM = re.compile(r'^FB_IMPL_MSG_NO_SYMBOL\((\w+), (\d+), "((?:[^"\\]|\\.)*)"\)')

def cs(s):
    return '"' + s.replace('\\"', '"').replace('\\', '\\\\').replace('"', '\\"') + '"'

rows = []
for fac, num in FACILITIES.items():
    for line in open(os.path.join(sys.argv[1], fac.lower() + ".h"), encoding="utf-8"):
        m = MSG.match(line)
        if not m:
            n = NOSYM.match(line)
            if n and n.group(3):
                code = 0x14000000 | (num << 16) | int(n.group(2))
                rows.append((code, f"{fac.lower()}_{n.group(2)}", -901, "", n.group(3)))
            continue
        code = 0x14000000 | (num << 16) | int(m.group(2))
        rows.append((code, m.group(3), int(m.group(4)), m.group(5) + m.group(6), m.group(7)))

seen = set()
print("""// <auto-generated> by tools/genmsg.py from Firebird's src/include/firebird/impl/msg/*.h </auto-generated>
//
// The message texts, SQLCODEs and SQLSTATEs come from the Firebird Open Source RDBMS project and are subject
// to the Initial Developer's Public License Version 1.0 (https://www.firebirdsql.org/en/initial-developer-s-public-license-version-1-0/).

namespace Fakebird;

/// <summary>Firebird status codes (isc_*), with message template, SQLCODE and SQLSTATE.</summary>
internal static class FbMessages
{""")
for code, sym, sqlcode, state, text in rows:
    if sym in seen:
        continue
    seen.add(sym)
    print(f"    public const int {sym} = {code};")
print("""
    public readonly record struct Info(string Symbol, int SqlCode, string SqlState, string Text);

    public static readonly Dictionary<int, Info> ByCode = new()
    {""")
for code, sym, sqlcode, state, text in rows:
    print(f"        [{code}] = new({cs(sym)}, {sqlcode}, {cs(state)}, {cs(text)}),")
print("""    };
}""")
