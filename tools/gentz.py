#!/usr/bin/env python3
"""Generates src/Fakebird/Types/TimeZoneList.g.cs: Firebird's built-in time zone list, whose order fixes the zone
ids (65535 - index), from Firebird's src/common/TimeZones.h.

usage: tools/gentz.py <firebird-source>/src/common/TimeZones.h > src/Fakebird/Types/TimeZoneList.g.cs
"""
import re, sys

names = re.findall(r'^\s*"([^"]+)",?\s*//', open(sys.argv[1]).read(), re.M)
print("""// <auto-generated> by tools/gentz.py from Firebird's src/common/TimeZones.h </auto-generated>
// The time zone list is part of Firebird (Initial Developer's Public License).

namespace Fakebird.Types;

internal static class TimeZoneList
{
    /// <summary>Region names in Firebird's order: the zone id of Names[i] is 65535 - i.</summary>
    public static readonly string[] Names =
    [""")
for i in range(0, len(names), 6):
    print("        " + " ".join(f'"{n}",' for n in names[i:i + 6]))
print("""    ];
}""")
