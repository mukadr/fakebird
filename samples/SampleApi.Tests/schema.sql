-- The production schema script (normally the same file you deploy to Firebird).
CREATE TABLE PRODUCT (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  NAME VARCHAR(100) NOT NULL UNIQUE,
  PRICE NUMERIC(12,2) NOT NULL CHECK (PRICE >= 0),
  STOCK INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE ORDERS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  PRODUCT_ID INTEGER NOT NULL REFERENCES PRODUCT(ID),
  QUANTITY INTEGER NOT NULL,
  TOTAL NUMERIC(14,2) NOT NULL,
  CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE VIEW SALES_REPORT (PRODUCT_NAME, UNITS, REVENUE) AS
  SELECT P.NAME, SUM(O.QUANTITY), SUM(O.TOTAL)
  FROM ORDERS O JOIN PRODUCT P ON P.ID = O.PRODUCT_ID
  GROUP BY P.NAME;

CREATE EXCEPTION E_BAD_QUANTITY 'quantity must be positive';

SET TERM ^ ;
CREATE TRIGGER ORDERS_BI FOR ORDERS BEFORE INSERT AS
BEGIN
  IF (NEW.QUANTITY <= 0) THEN EXCEPTION E_BAD_QUANTITY;
END^
SET TERM ; ^

